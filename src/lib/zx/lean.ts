/** Lean 4-style formalization of qudit ZX rewrite rules (display + operational spec). */

export const QUDIT_ZX_LEAN = `namespace QuditZX

/-- Dimension of the qudit. -/
variable (d : ℕ) [NeZero d]

/-- Spider colour. -/
inductive Colour | Z | X
  deriving DecidableEq, Repr

/-- A finite phase in ℤ/dℤ. -/
abbrev Phase := Fin d

/-- A spider: colour, phase, and arity (number of legs). -/
structure Spider where
  colour : Colour
  phase  : Phase
  arity  : ℕ
  deriving Repr

/-- A ZX diagram over qudits of dimension d. -/
structure Diagram where
  spiders : List Spider
  -- undirected wires between spider indices
  wires   : List (ℕ × ℕ)
  scalar  : ℕ          -- tracked in ℤ, later reduced mod the global phase
  deriving Repr

/-- Fourier gate on ℂ^d. -/
def F : Matrix (Fin d) (Fin d) ℂ :=
  Matrix.of fun i j =>
    Complex.exp (2 * Real.pi * Complex.I * i.val * j.val / d) / Real.sqrt d

/-- Spider fusion: two same-colour spiders joined by ≥1 wire become one
    spider whose phase is the sum. -/
axiom fuse
  (Γ : Diagram) (i j : ℕ)
  (h_col : (Γ.spiders.get! i).colour = (Γ.spiders.get! j).colour)
  (h_wire : (i, j) ∈ Γ.wires ∨ (j, i) ∈ Γ.wires) :
  ∃ Γ', equivalent Γ Γ'
    ∧ (Γ'.spiders.get! i).phase
        = (Γ.spiders.get! i).phase + (Γ.spiders.get! j).phase

/-- Identity: a phase-0 spider of arity 2 is a straight wire. -/
axiom identity_rule
  (s : Spider) (h : s.phase = 0 ∧ s.arity = 2) :
  equivalent (singleton s) wire

/-- Hopf law (qudit): two parallel wires between a Z-spider and an X-spider
    evaluate to the scalar d and disconnect. -/
axiom hopf
  (z x : Spider)
  (hz : z.colour = Colour.Z) (hx : x.colour = Colour.X) :
  equivalent
    { spiders := [z, x], wires := [(0,1), (0,1)], scalar := 1 }
    { spiders := [z, x], wires := [],            scalar := d }

/-- Colour change: conjugating every leg of a Z-spider by F yields an
    X-spider of the same phase (Weyl duality). -/
axiom colour_change (s : Spider) (h : s.colour = Colour.Z) :
  equivalent (applyF s) { s with colour := Colour.X }

/-- π-copy / computational-basis copy: a phase-0 Z-spider copies
    computational-basis states onto every output. -/
axiom z_copy (k : Fin d) :
  apply (zSpider 0 (n+1)) (basis k ⊗ ⋯)
    = Tensor.replicate n (basis k)

/-- Completeness: on the Clifford fragment generated by F and the Weyl
    operators W(m,n) = X^m Z^n, the rewrite system decides equality. -/
axiom clifford_complete (Γ Δ : Diagram) :
  (toLinearMap Γ = toLinearMap Δ) ↔ rewriteReachable Γ Δ

end QuditZX
`;
